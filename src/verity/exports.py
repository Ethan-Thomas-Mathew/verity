"""Turn approved test specs and bug reports into files other tools use.

- Postman collection: run the API regression suite with Postman or Newman.
- pytest module: the same suite as plain Python code that runs without Verity.
- Test case CSV: manual test cases for a test management sheet.
- Jira CSV: bug reports in a shape Jira's CSV importer accepts.

All of these are generated by code from validated specs. No model is involved,
so an export always matches exactly what was reviewed.
"""

import csv
import io
import json
import re
from collections.abc import Iterable
from typing import Any

from verity.runners.api_runner import VARIABLE
from verity.runners.specs import ApiStep, ApiTest, UiTest, manual_steps

# ---------------------------------------------------------------- Postman


def _postman_raw_body(body: dict[str, Any]) -> str:
    # "{{id}}" as a whole JSON value becomes a bare {{id}}, so Postman inserts
    # the saved number as a number instead of the string "7".
    raw = json.dumps(body, indent=2)
    return re.sub(r'"\{\{\s*(\w+)\s*\}\}"', r"{{\1}}", raw)


def _postman_tests(step: ApiStep) -> list[str]:
    lines = [
        "const read = (data, path) => path.split('.').reduce("
        "(cur, key) => (cur == null ? undefined : cur[key]), data);",
        f"pm.test({json.dumps(f'status is {step.expect.status}')}, () => "
        f"pm.response.to.have.status({step.expect.status}));",
    ]
    for path, value in step.expect.fields.items():
        lines.append(
            f"pm.test({json.dumps(f'{path} is {json.dumps(value)}')}, () => "
            f"pm.expect(read(pm.response.json(), {json.dumps(path)})).to.eql({json.dumps(value)}));"
        )
    if step.expect.length is not None:
        lines.append(
            f"pm.test({json.dumps(f'has {step.expect.length} items')}, () => "
            f"pm.expect(pm.response.json()).to.have.lengthOf({step.expect.length}));"
        )
    for name, path in step.save.items():
        lines.append(
            f"pm.collectionVariables.set({json.dumps(name)}, read(pm.response.json(), "
            f"{json.dumps(path)}));"
        )
    return lines


def _postman_request(name: str, step: ApiStep) -> dict[str, Any]:
    path = [p for p in step.path.split("/") if p]
    url: dict[str, Any] = {
        "raw": "{{baseUrl}}" + step.path,
        "host": ["{{baseUrl}}"],
        "path": path,
    }
    if step.params:
        url["query"] = [{"key": k, "value": v} for k, v in step.params.items()]
        url["raw"] += "?" + "&".join(f"{k}={v}" for k, v in step.params.items())
    request: dict[str, Any] = {"method": step.method, "url": url, "header": []}
    if step.body is not None:
        request["header"] = [{"key": "Content-Type", "value": "application/json"}]
        request["body"] = {"mode": "raw", "raw": _postman_raw_body(step.body)}
    return {
        "name": name,
        "request": request,
        "event": [
            {"listen": "test", "script": {"type": "text/javascript", "exec": _postman_tests(step)}}
        ],
    }


def postman_collection(tests: Iterable[ApiTest], base_url: str) -> dict[str, Any]:
    folders = []
    for test in tests:
        reset = {
            "name": "Reset test data",
            "request": {
                "method": "POST",
                "url": {
                    "raw": "{{baseUrl}}/api/test/reset",
                    "host": ["{{baseUrl}}"],
                    "path": ["api", "test", "reset"],
                },
                "header": [],
            },
            "event": [
                {
                    "listen": "test",
                    "script": {
                        "type": "text/javascript",
                        "exec": ["pm.test('reset', () => pm.response.to.have.status(204));"],
                    },
                }
            ],
        }
        steps = [
            _postman_request(f"Step {n}: {s.method} {s.path}", s)
            for n, s in enumerate(test.steps, start=1)
        ]
        folders.append({"name": f"{test.requirement_id}: {test.title}", "item": [reset, *steps]})
    return {
        "info": {
            "name": "Verity regression suite",
            "schema": "https://schema.getpostman.com/json/collection/v2.1.0/collection.json",
        },
        "variable": [{"key": "baseUrl", "value": base_url}],
        "item": folders,
    }


# ---------------------------------------------------------------- pytest


def _py_value(value: Any) -> str:
    """Python source for a spec value, with {{name}} placeholders read from `saved`."""
    if isinstance(value, dict):
        return "{" + ", ".join(f"{k!r}: {_py_value(v)}" for k, v in value.items()) + "}"
    if isinstance(value, list):
        return "[" + ", ".join(_py_value(v) for v in value) + "]"
    if isinstance(value, str):
        whole = VARIABLE.fullmatch(value.strip())
        if whole:
            return f"saved[{whole.group(1)!r}]"
        if VARIABLE.search(value):
            template = value.replace("{", "{{").replace("}", "}}")
            template = re.sub(r"\{\{\{\{\s*(\w+)\s*\}\}\}\}", r"{saved['\1']}", template)
            return f"f{template!r}"
    return repr(value)


def _identifier(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")[:60]


def _py_steps(steps: list[ApiStep], indent: str) -> list[str]:
    lines = []
    for n, step in enumerate(steps, start=1):
        args = [repr(step.method), _py_value(step.path)]
        if step.params:
            args.append(f"params={_py_value(step.params)}")
        if step.body is not None:
            args.append(f"json={_py_value(step.body)}")
        lines += [
            f"{indent}# step {n}",
            f"{indent}response = client.request({', '.join(args)})",
            f"{indent}assert response.status_code == {step.expect.status}, response.text",
        ]
        if step.expect.fields or step.expect.length is not None or step.save:
            lines.append(f"{indent}data = response.json()")
        if step.expect.length is not None:
            lines.append(f"{indent}assert len(data) == {step.expect.length}")
        lines += [
            f"{indent}assert read(data, {path!r}) == {value!r}"
            for path, value in step.expect.fields.items()
        ]
        lines += [
            f"{indent}saved[{name!r}] = read(data, {path!r})" for name, path in step.save.items()
        ]
    return lines


def pytest_module(api_tests: Iterable[ApiTest], ui_tests: Iterable[UiTest]) -> str:
    out = [
        '"""Regression tests exported by Verity from approved test cases.',
        "",
        "Regenerate with `verity export pytest` instead of editing by hand.",
        "Set TARGET_URL to the app under test (default http://127.0.0.1:8001).",
        '"""',
        "",
        "import os",
        "from collections.abc import Iterator",
        "from typing import Any",
        "",
        "import httpx",
        "import pytest",
        "",
        'BASE_URL = os.environ.get("TARGET_URL", "http://127.0.0.1:8001")',
        "",
        "",
        "def read(data: Any, path: str) -> Any:",
        '    for key in path.split("."):',
        "        data = data[int(key)] if isinstance(data, list) else data[key]",
        "    return data",
        "",
        "",
        "@pytest.fixture",
        "def client() -> Iterator[httpx.Client]:",
        "    with httpx.Client(base_url=BASE_URL) as c:",
        '        assert c.post("/api/test/reset").status_code == 204',
        "        yield c",
    ]
    seen: set[str] = set()

    def name_for(test: ApiTest | UiTest) -> str:
        base = f"test_{_identifier(test.requirement_id)}_{_identifier(test.title)}"
        name, n = base, 2
        while name in seen:
            name, n = f"{base}_{n}", n + 1
        seen.add(name)
        return name

    for test in api_tests:
        out += ["", "", f"def {name_for(test)}(client: httpx.Client) -> None:"]
        out += [f"    {test.title!r}", "    saved: dict[str, Any] = {}"]
        out += _py_steps(test.steps, "    ")
    ui = list(ui_tests)
    if ui:
        out += [
            "",
            "",
            "@pytest.fixture",
            "def page() -> Iterator[Any]:",
            "    from playwright.sync_api import sync_playwright",
            "",
            "    with sync_playwright() as p:",
            '        executable = os.environ.get("BROWSER") or None',
            "        browser = p.chromium.launch(executable_path=executable)",
            "        yield browser.new_page()",
            "        browser.close()",
        ]
    for ui_test in ui:
        out += ["", "", f"def {name_for(ui_test)}(client: httpx.Client, page: Any) -> None:"]
        out += [f"    {ui_test.title!r}", "    from playwright.sync_api import expect", ""]
        out += ["    saved: dict[str, Any] = {}"]
        out += _py_steps(ui_test.setup, "    ")
        for action in ui_test.steps:
            target, value = _py_value(action.target), _py_value(action.value)
            match action.action:
                case "goto":
                    out.append(f"    page.goto(BASE_URL + {target})")
                case "fill":
                    out.append(f"    page.get_by_label({target}, exact=True).fill(str({value}))")
                case "click":
                    out.append(f'    page.get_by_role("button", name={target}).click()')
                    out.append('    page.wait_for_load_state("networkidle")')
                case "expect_text":
                    out.append(f'    expect(page.locator("body")).to_contain_text({value})')
                case "expect_no_text":
                    out.append(f'    expect(page.locator("body")).not_to_contain_text({value})')
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- CSV


def test_cases_csv(rows: Iterable[tuple[int, ApiTest | UiTest, str | None, str]]) -> str:
    """rows: (id, spec, outcome, review)."""
    buffer = io.StringIO()
    writer = csv.writer(buffer)
    writer.writerow(["ID", "Requirement", "Type", "Title", "Steps", "Outcome", "Review"])
    for case_id, test, outcome, review in rows:
        steps = "\n".join(f"{n}. {s}" for n, s in enumerate(manual_steps(test), start=1))
        kind = "API" if isinstance(test, ApiTest) else "UI"
        writer.writerow(
            [f"TC-{case_id}", test.requirement_id, kind, test.title, steps, outcome or "", review]
        )
    return buffer.getvalue()


def jira_csv(bugs: Iterable[dict[str, Any]]) -> str:
    """bugs: dicts with summary, severity, requirement_id, steps_to_reproduce, expected, actual."""
    priority = {"high": "High", "medium": "Medium", "low": "Low"}
    buffer = io.StringIO()
    writer = csv.writer(buffer)
    writer.writerow(["Summary", "Issue Type", "Priority", "Labels", "Description"])
    for bug in bugs:
        steps = "\n".join(f"# {s}" for s in bug["steps_to_reproduce"])
        description = (
            f"*Requirement:* {bug['requirement_id']}\n\n*Steps to reproduce:*\n{steps}\n\n"
            f"*Expected:* {bug['expected']}\n\n*Actual:* {bug['actual']}"
        )
        writer.writerow([bug["summary"], "Bug", priority[bug["severity"]], "verity", description])
    return buffer.getvalue()
